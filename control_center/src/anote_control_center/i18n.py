def validate_catalogs() -> None:
    english = set(CATALOGS["en"])
    spanish = set(CATALOGS["es"])
    if english != spanish:
        missing_en = sorted(spanish - english)
        missing_es = sorted(english - spanish)
        raise ContractError(
            f"Translation catalogs differ; missing English={missing_en}, missing Spanish={missing_es}.",
            code="translation_catalog_invalid",
        )


@dataclass
class Translator:
    language: Language = "en"

    def __post_init__(self) -> None:
        validate_catalogs()
        if self.language not in CATALOGS:
            raise ContractError("Language is unsupported.", code="language_invalid")

    def text(self, key: str, **values: object) -> str:
        try:
            template = CATALOGS[self.language][key]
        except KeyError as error:
            raise ContractError(f"Translation key is missing: {key}.", code="translation_catalog_invalid") from error
        return template.format(**values)

    def error(self, code: str) -> str:
        return CATALOGS[self.language].get(f"error.{code}", CATALOGS[self.language]["error.default"])
